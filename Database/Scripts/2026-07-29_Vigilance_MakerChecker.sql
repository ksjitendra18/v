/*
    Vigilance Maker-Checker
    =================================================================================
    Database : VigilanceMISDB
    Requires : 2026-07-27_CaseApproval_Central_MakerChecker_Foundation.sql

    Puts the VIGILANCE module on the central CASE_APPROVAL registry, following the
    recipe in Docs/VMIS_IAC_MakerChecker_Implementation.md sec 9.

    No column is added to VIGILANCE or VIGILANCE_HISTORY. That matters more here than
    anywhere else: the two tables are 171 columns each and spVigilance_Update,
    spVigilanceUser_Update and spVigilanceExcel_Import all copy history with
    INSERT INTO VIGILANCE_HISTORY SELECT * FROM VIGILANCE, which only works while both
    tables stay in exact ordinal alignment.

    Changes
    -------
    0. Registry  : VIGILANCE added to WORKFLOW_MODULE (key CODE, ref RNO, zone NEWZONE).
    1. Backfill  : existing VIGILANCE rows are grandfathered as Approved (see note below).
    2. spVigilance_Update
         insert -> registers the record as Pending and logs SUBMITTED
         update -> blocked when Pending or Rejected; re-queued to Pending (+ RESUBMITTED)
                   when the prior status was Approved or Changes Requested
         both   -> Zone (New) is now mandatory for a maker, because the zone is what
                   routes the record to a checker. Without it the record would sit
                   Pending forever, invisible to every inbox and locked from editing.
         Both entry pages (Mis/frmVigilance.aspx and Mis/Vigilance.aspx) call this one
         procedure, so enforcing here covers both.
    3. spVigilance_View : LIST / SEARCH / GET now return APPROVALSTATUS,
                          APPROVALSTATUSTEXT and CHECKERREMARKS.
    4. spVigilanceUser_Update : closes the bypass -- changing Basic Pay / DA_CO-ZO-HO /
                          Register / Penalty Proceeding on an approved record now sends
                          it back to the checker instead of leaving it approved and
                          unverified.

    No procedure signature changes, so every existing C# call site keeps working.
    New @o_ERRCODE values on spVigilance_Update: 4 = zone missing, 5 = record locked.

    Backfill note
    -------------
    Step 1 marks every pre-existing VIGILANCE row Approved, on the basis that those
    records predate the control and were never anyone's to check. Flipping them to 'P'
    instead would flood the checker inbox and lock every existing record from editing.
    Change the literal in step 1 if the business wants the opposite.

    Safe to re-run.
*/

