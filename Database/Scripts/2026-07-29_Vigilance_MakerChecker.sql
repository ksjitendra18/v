-- 0. Register VIGILANCE in the module registry
--
--    KeyColumn  CODE    -> CASE_APPROVAL.RecordCode  (int identity surrogate)
--    RefColumn  RNO     -> CASE_APPROVAL.RecordRef   (the R Number a user sees)
--    ZoneColumn NEWZONE -> CASE_APPROVAL.ZoneSolID   (routes the record to a checker)
-------------------------------------------------------------------------------------------------
MERGE dbo.WORKFLOW_MODULE AS T
USING (VALUES
        ('VIGILANCE', 'Vigilance', 'VIGILANCE', 'CODE', 'RNO', 'NEWZONE', '~/Mis/frmVigilanceCheckerView.aspx', 1)
      ) AS S (ModuleCode, ModuleName, TableName, KeyColumn, RefColumn, ZoneColumn, ViewPage, IsActive)
   ON T.ModuleCode = S.ModuleCode
WHEN MATCHED THEN UPDATE SET
        T.ModuleName = S.ModuleName,
        T.TableName  = S.TableName,
        T.KeyColumn  = S.KeyColumn,
        T.RefColumn  = S.RefColumn,
        T.ZoneColumn = S.ZoneColumn,
        T.ViewPage   = S.ViewPage,
        T.IsActive   = S.IsActive
WHEN NOT MATCHED THEN
    INSERT (ModuleCode, ModuleName, TableName, KeyColumn, RefColumn, ZoneColumn, ViewPage, IsActive)
    VALUES (S.ModuleCode, S.ModuleName, S.TableName, S.KeyColumn, S.RefColumn, S.ZoneColumn, S.ViewPage, S.IsActive);
GO

-------------------------------------------------------------------------------------------------
-- 1. Backfill: grandfather pre-existing VIGILANCE records
-------------------------------------------------------------------------------------------------
INSERT INTO dbo.CASE_APPROVAL
    (ModuleCode, RecordCode, RecordRef, ZoneSolID, ApprovalStatus, MakerUser, MakerDate, CheckerUser, CheckerDate, CheckerRemarks)
SELECT  'VIGILANCE',
        V.CODE,
        V.RNO,
        V.NEWZONE,
        'A',
        ISNULL(V.ADDUSER, 'SYSTEM'),
        ISNULL(V.ADDDATE, GETDATE()),
        'SYSTEM',
        GETDATE(),
        'Pre-existing record grandfathered at maker-checker rollout.'
FROM    dbo.VIGILANCE V
WHERE   V.ACTIVE = 'Y'
  AND   NOT EXISTS (SELECT 1 FROM dbo.CASE_APPROVAL CA
                    WHERE CA.ModuleCode = 'VIGILANCE' AND CA.RecordCode = V.CODE);
GO

INSERT INTO dbo.CASE_APPROVAL_HISTORY (ModuleCode, RecordCode, ActionType, ActionBy, Remarks)
SELECT  'VIGILANCE', CA.RecordCode, 'GRANDFATHERED', 'SYSTEM',
        'Pre-existing record grandfathered at maker-checker rollout.'
FROM    dbo.CASE_APPROVAL CA
WHERE   CA.ModuleCode = 'VIGILANCE'
  AND   CA.CheckerUser = 'SYSTEM'
  AND   NOT EXISTS (SELECT 1 FROM dbo.CASE_APPROVAL_HISTORY H
                    WHERE H.ModuleCode = 'VIGILANCE' AND H.RecordCode = CA.RecordCode
                      AND H.ActionType = 'GRANDFATHERED');
GO

