-- 4. dbo.spVigilanceUser_Update  -- close the bulk-update bypass
--
--    This proc (Mis/frmVigilanceUpdate.aspx, MISUSER-only) changes Basic Pay, DA_CO/ZO/HO,
--    Register or Penalty Proceeding on an existing record. It never touched the approval
--    state, so a maker could alter an approved record and it stayed approved and
--    unverified. Now the change re-queues the record.
--
--    @p_USERROLE / @p_USERIP are appended with defaults so the existing call site, which
--    passes nine parameters, keeps working untouched.
-------------------------------------------------------------------------------------------------
CREATE OR ALTER PROC [dbo].[spVigilanceUser_Update]
(
	@p_RNO		VARCHAR(50),
	@p_DACOZOHO	VARCHAR(100),
	@p_BASICPAY	VARCHAR(100),
	@p_FIELD	VARCHAR(50),
	@p_REGISTER	VARCHAR(50),
	@p_PENALTYPROCEEDING BIGINT,
	@p_USER		VARCHAR(50),
	@o_EERMSG	VARCHAR(MAX) OUTPUT,
	@o_ERRCODE	INT OUTPUT,
	@p_USERROLE	VARCHAR(50)=NULL,
	@p_USERIP	VARCHAR(30)=NULL
)
AS
BEGIN
	DECLARE @CODE BIGINT, @OLDAPPROVALSTATUS CHAR(1);

	SET @o_ERRCODE=0;
	IF(@p_RNO <> '')
		BEGIN
			SELECT @CODE = CODE FROM VIGILANCE WHERE RNO=@p_RNO AND ACTIVE='Y';

			IF(@CODE IS NOT NULL)
				BEGIN
					IF(@p_FIELD <> 'SELECT')
						BEGIN
							SELECT @OLDAPPROVALSTATUS = ApprovalStatus
							FROM   CASE_APPROVAL
							WHERE  ModuleCode='VIGILANCE' AND RecordCode=@CODE;

							--A REJECTED RECORD IS NOT EDITABLE THROUGH ANY PATH.
							IF(@OLDAPPROVALSTATUS = 'X')
								BEGIN
									SET @o_ERRCODE=3;
									SET @o_EERMSG= 'This record has been rejected by the checker and cannot be edited......!';
									RETURN;
								END

						  BEGIN TRY
							BEGIN TRAN;

							--UPDATE TBALE VIGILANCE_HISTORY
							INSERT INTO VIGILANCE_HISTORY SELECT * FROM VIGILANCE WHERE RNO=@p_RNO;

							IF(@p_FIELD = 'BASICPAY')
								BEGIN
									UPDATE VIGILANCE SET BASICPAY=@p_BASICPAY,MODUSER=@p_USER,MODDATE=GETDATE() WHERE RNO=@p_RNO;
									SET @o_ERRCODE=1;
									SET @o_EERMSG= 'Basic Pay Updated Sucessfully......!';
								END

							ELSE IF(@p_FIELD = 'DA_CO_ZO_HO')
								BEGIN
									UPDATE VIGILANCE SET DISAUTHORITYSCIRCLE=@p_DACOZOHO,MODUSER=@p_USER,MODDATE=GETDATE() WHERE RNO=@p_RNO;
									SET @o_ERRCODE=1;
									SET @o_EERMSG= 'DA_CO/ZO/HO Updated Sucessfully......!';
								END

							ELSE IF(@p_FIELD = 'REGISTER')
								BEGIN
									UPDATE VIGILANCE SET REGISTER=@p_REGISTER,MODUSER=@p_USER,MODDATE=GETDATE() WHERE RNO=@p_RNO;
									SET @o_ERRCODE=1;
									SET @o_EERMSG= 'Register Updated Sucessfully......!';
								END

							ELSE IF(@p_FIELD = 'PENALTYPROCEEDING')
								BEGIN
									UPDATE VIGILANCE SET PENALTYPROCEEDING=@p_PENALTYPROCEEDING,MODUSER=@p_USER,MODDATE=GETDATE() WHERE RNO=@p_RNO;
									SET @o_ERRCODE=1;
									SET @o_EERMSG= 'Penalty Proceeding Updated Sucessfully......!';
								END

							--MAKER-CHECKER: THE EDIT INVALIDATES ANY EARLIER DECISION, SO SEND IT BACK
							--TO THE CHECKER RATHER THAN LEAVING IT APPROVED AND UNVERIFIED.
							IF(@o_ERRCODE = 1 AND @OLDAPPROVALSTATUS IN ('A','C'))
								BEGIN
									UPDATE CASE_APPROVAL
									   SET ApprovalStatus = 'P',
										   MakerUser      = @p_USER,
										   MakerDate      = GETDATE(),
										   CheckerUser    = NULL,
										   CheckerDate    = NULL,
										   CheckerRemarks = NULL
									 WHERE ModuleCode='VIGILANCE' AND RecordCode=@CODE;

									INSERT INTO CASE_APPROVAL_HISTORY
										(ModuleCode, RecordCode, ActionType, ActionBy, Remarks, UserRole, UserIP)
									VALUES
										('VIGILANCE', @CODE, 'RESUBMITTED', @p_USER,
										 @p_FIELD + ' changed via Vigilance Update screen.', @p_USERROLE, @p_USERIP);
								END

							COMMIT TRAN;
						  END TRY
						  BEGIN CATCH
							IF (XACT_STATE() <> 0) ROLLBACK TRAN;
							SET @o_ERRCODE=0;
							SET @o_EERMSG= 'Could not update the record: ' + ERROR_MESSAGE();
						  END CATCH
						END
				END
			ELSE
				BEGIN
					SET @o_ERRCODE=2;
					SET @o_EERMSG= 'Invalid Vigilance (R) Number......!';
				END
		END
END
